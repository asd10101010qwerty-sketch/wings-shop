export function formatCurrency(amount: number, locale: Locale = 'uz'): string {
  const formattedNumber = new Intl.NumberFormat(locale === 'en' ? 'en-US' : 'ru-RU', {
    maximumFractionDigits: 0,
  })
    .format(amount)
    .replace(/\u00a0/g, ' ');

  if (locale === 'uz') {
    return `${formattedNumber} soʻm`;
  }
  if (locale === 'ru') {
    return `${formattedNumber} сум`;
  }
  return `${formattedNumber} UZS`;
}
